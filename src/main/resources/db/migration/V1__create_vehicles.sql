create table vehicles (
    id               bigint generated by default as identity primary key,
    plate            varchar(8)  not null,
    brand            varchar(50) not null,
    model            varchar(50) not null,
    manufacture_year integer     not null,
    status           varchar(20) not null,
    mileage_km       integer     not null,
    constraint uk_vehicles_plate unique (plate),
    constraint ck_vehicles_status check (status in ('available', 'in_service', 'maintenance'))
);

-- A constraint unique já cria um índice em plate (serve o existsByPlate e as pesquisas por matrícula exata).
